# Random rollouts everywhere they are not the subject, because they cost about a
# fourteenth of what a greedy rollout costs (15.1 positions a simulation against 214.3,
# measured in `data/results/mcts_cost.csv`) and this suite is run on every commit.
FAST = RANDOM


def mcts(simulations=200, playout=FAST, seed=2026) -> MctsAgent:
    agent = MctsAgent(simulations, playout=playout, seed=seed)
    agent.new_game(seed)
    return agent


def sample(count: int, predicate, seed: int = 11) -> list[NaiveBoard]:
    """Positions satisfying `predicate`, drawn the way every property test here draws."""
    rng = random.Random(seed)
    found = []
    while len(found) < count:
        board = random_position(rng)
        if not board.is_terminal() and predicate(board):
            found.append(board)
    return found


