def test_a_node_budget_stops_the_search_and_a_simulation_budget_caps_it():
    board = Bitboard.from_move_string("44")
    _, stats = mcts(100_000).choose_move(board, Budget(nodes=2_000))
    assert stats.simulations < 100_000
    # One simulation may cross the line; it cannot cross it by more than one simulation.
    assert stats.nodes <= 2_000 + stats.nodes / stats.simulations * 2

    _, capped = mcts(37).choose_move(board, Budget(nodes=10_000_000))
    assert capped.simulations == 37


def test_a_legal_move_comes_back_even_with_no_time_at_all():
    """Phase 9's rule, applied to a different algorithm: the first unit of work is
    uninterruptible, because without it there is no answer to give."""
    board = Bitboard.from_move_string("4455")
    move, stats = mcts(100_000).choose_move(board, Budget(time=0.0))
    assert move in board.legal_moves()
    assert stats.simulations == 1

    move, stats = mcts(100_000).choose_move(board, Budget(nodes=0))
    assert move in board.legal_moves()
    assert stats.simulations == 1


# ------------------------------------------------- the sign flip, and what it protects


def test_a_child_that_wins_on_the_spot_is_worth_exactly_one_and_is_the_move_played():
    """The sign flip in backpropagation is this phase's `child_not_negated`: a result
    pushed up without being flipped produces an agent that plays for the wrong side and
    still looks plausible from the outside. This is the sharpest thing that notices.

    From a position with a win in one, the winning child is terminal, so its reward is the
    exact value 1.0 on every single visit and its mean can only be 1.0 -- unless the flip
    is wrong, in which case it is 0.0 and the move is the last one the search would play.
    """
    board = Bitboard.from_move_string("112233")
    move, stats = mcts(400).choose_move(board)
    assert move == 3
    assert stats.win_rate == pytest.approx(1.0)
    assert stats.leaves > 0  # it was answered exactly, never rolled out


def test_a_move_that_hands_over_an_immediate_win_attracts_the_fewest_visits():
    """The other side of the same coin, and it needs the flip to be right one level
    further up rather than at the leaf.

    A column after which the opponent can win at once is not itself terminal -- the
    badness has to travel up through a flip to be seen at all. So over positions where a
    safe column and an unsafe one both exist, the safe side must attract more visits.
    """
    boards = sample(
        8,
        lambda board: not winning_columns(board)
        and 0 < len(safe_columns(board)) < len(board.legal_moves()),
    )
    agent = mcts(800)
    preferred = 0
    for board in boards:
        agent.new_game(2026)
        _, stats = agent.choose_move(board)
        safe = safe_columns(board)
        unsafe = [col for col in board.legal_moves() if col not in safe]
        preferred += max(stats.visits[c] for c in safe) > max(stats.visits[c] for c in unsafe)
    assert preferred == len(boards)


def test_it_beats_the_random_agent_convincingly():
    """The coarsest possible check that the whole loop points the right way. A sign flip
    anywhere in it turns this into a heavy loss rather than a narrow one."""
    match = play_match(mcts(150), RandomAgent(seed=3), games=60, seed=2026, opening_plies=4)
    assert match.overall.score > 0.9


# ----------------------------------------------------- tactics: statistical for plain UCT


def test_it_takes_a_win_in_one_nearly_always():
    """STATISTICAL, and the floor is deliberately under the measured rate. A winning child
    scores 1.0 on every visit so nothing can beat its mean -- but the root answers with the
    most *visited* child, and at a small budget those are not the same question. Measured
    over 150 positions: 98.0% at 100 simulations and 100.0% at 250 (random rollouts)."""
    boards = sample(60, lambda board: bool(winning_columns(board)))
    agent = mcts(250)
    hits = 0
    for board in boards:
        agent.new_game(2026)
        move, _ = agent.choose_move(board)
        hits += move in winning_columns(board)
    assert hits >= 0.93 * len(boards)


def test_it_blocks_a_win_in_one_nearly_always():
    """STATISTICAL, same shape. `safe_columns` is the correct statement of the property
    and Phase 4 audited the greedy agent against exactly it: 'play the column the opponent
    would win in' is wrong, because filling their cell can open a new win above it."""
    boards = sample(
        60,
        lambda board: not winning_columns(board)
        and 0 < len(safe_columns(board)) < len(board.legal_moves()),
    )
    agent = mcts(250)
    hits = 0
    for board in boards:
        agent.new_game(2026)
        move, _ = agent.choose_move(board)
        hits += move in safe_columns(board)
    assert hits >= 0.85 * len(boards)


# --------------------------------------------------- the solver: the same thing, provable


def test_with_the_solver_a_win_in_one_is_never_missed_rather_than_almost_never():
    """PROVABLE, and this is the whole reason the switch exists.

    Expansion is exhaustive and takes the children in a fixed order, so after at most
    seven simulations every child of the root exists. A child that wins is terminal and is
    proven the moment it is created, and a proven win outranks every average at the root.
    So the property holds for every position, not for 99.3% of a sample -- and the sample
    is only there to demonstrate it.
    """
    boards = sample(60, lambda board: bool(winning_columns(board)))
    agent = MctsAgent(COLS, playout=SOLVER, seed=2026)
    for board in boards:
        agent.new_game(2026)
        move, stats = agent.choose_move(board)
        assert move in winning_columns(board), board
        assert stats.value == Score.WIN


def test_the_solver_stops_as_soon_as_the_position_is_settled():
    """A proof is not an average: once the root is decided there is nothing more to
    sample, so the budget is not spent."""
    agent = MctsAgent(5_000, playout=SOLVER, seed=2026)
    agent.new_game(2026)
    _, stats = agent.choose_move(Bitboard.from_move_string("112233"))
    assert stats.simulations <= COLS
    assert stats.value == Score.WIN


def test_without_the_solver_nothing_is_ever_claimed_to_be_proven():
    """Plain UCT averages; it does not prove. The exact value of a terminal node is still
    used -- that is not an enhancement, it is the absence of a mistake -- but it is never
    propagated and never reported as a certainty."""
    agent = mcts(300)
    _, stats = agent.choose_move(Bitboard.from_move_string("112233"))
    assert stats.value is None


def test_the_solver_proves_a_loss_as_well_as_a_win():
    """Proving a loss is the harder half: it needs *every* child settled, not one. The
    fixture is found rather than asserted to exist -- a position where every legal column
    hands the opponent a win in one, which Phase 4 measured greedy walking into 133 times
    in 3,000 games."""
    doomed = sample(1, lambda board: not winning_columns(board) and not safe_columns(board))
    board = Bitboard.from_move_string(
        "".join(str(col + 1) for col in doomed[0].history)
    )
    agent = MctsAgent(5_000, playout=SOLVER, seed=2026)
    agent.new_game(2026)
    _, stats = agent.choose_move(board)
    assert stats.value == Score.LOSS
    assert stats.simulations < 5_000  # it stopped as soon as the position was settled


# ------------------------------------------------------------------- convergence


def test_the_visits_concentrate_on_a_move_that_keeps_a_forced_win():
    """The one way the 1,050-record file is still usable as a correctness net here.

    Take the records whose stored value is a forced *result* rather than a heuristic
    score, work out which moves preserve it with a search, and ask whether the visit
    distribution settles on one of them. Forced losses are excluded: every move loses, so
    the property would be satisfied by anything. STATISTICAL -- the measured rate is in
    `data/results/mcts_convergence.csv` and the floor here sits under it.
    """
    data = reference.load()
    records = [
        record for record in data["records"]
        if record["depth"] == 5 and record["value"] >= Score.MIN_WIN
    ][:12]
    assert len(records) == 12, "the reference file no longer holds enough forced wins"

    prober = NegamaxAgent(4, seed=2026)
    agent = mcts(2_000)
    hits = 0
    for record in records:
        board = Bitboard.from_move_string(record["moves"])
        keep = []
        for col in board.legal_moves():
            board.play(col)
            if board.winner() is not None:
                keep.append(col)
            elif not board.is_terminal() and -prober.choose_move(board)[1].value >= Score.MIN_WIN:
                keep.append(col)
            board.undo()
        agent.new_game(2026)
        move, _ = agent.choose_move(board)
        hits += move in keep
    assert hits >= 9


