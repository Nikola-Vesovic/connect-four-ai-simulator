# --------------------------------------------------------------- reproducibility, provable


def _fingerprint(stats) -> tuple:
    return (
        stats.move, stats.nodes, stats.simulations, stats.rollouts, stats.leaves,
        stats.depth, stats.visits, stats.root_visits, stats.root_reward, stats.tree_nodes,
    )


def test_the_same_seed_and_the_same_budget_reproduce_the_move_and_every_counter():
    board = Bitboard.from_move_string("4455")
    runs = []
    for _ in range(3):
        _, stats = mcts(500).choose_move(board)
        runs.append(_fingerprint(stats))
    assert runs[0] == runs[1] == runs[2]


def test_a_different_seed_grows_a_different_tree():
    board = Bitboard.from_move_string("4455")
    _, one = mcts(500, seed=1).choose_move(board)
    _, two = mcts(500, seed=2).choose_move(board)
    assert one.visits != two.visits


def test_with_greedy_rollouts_the_seed_changes_nothing_at_all():
    """Not a bug and worth a test rather than a footnote: every tie-break in this search
    is deterministic, so the only consumer of randomness is the rollout policy. The greedy
    policy has none, which makes the whole agent deterministic -- and means it needs
    `play_match(opening_plies=...)` like every other agent since Phase 5."""
    board = Bitboard.from_move_string("4455")
    _, one = mcts(120, playout=UCT, seed=1).choose_move(board)
    _, two = mcts(120, playout=UCT, seed=99).choose_move(board)
    assert _fingerprint(one) == _fingerprint(two)


def test_a_new_game_throws_the_tree_away():
    agent = MctsAgent(200, playout=replace(FAST, reuse=True), seed=5)
    agent.new_game(5)
    board = Bitboard()
    agent.choose_move(board)
    board.play(3)
    _, kept = agent.choose_move(board)
    assert kept.tree_reused > 0
    agent.new_game(5)
    _, fresh = agent.choose_move(board)
    assert fresh.tree_reused == 0


