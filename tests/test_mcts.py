"""Phase 11 -- Monte Carlo tree search with UCT.

**The gate of every phase since Phase 6 is useless here and that is the first thing to
say.** Those phases were the same search made faster, so correctness was one repeated
equality: replay the 1,050 frozen minimax values and disagree with none of them. MCTS
never computes a minimax value. It does not search to a fixed depth, it never calls the
evaluation function, and it plays different moves on purpose. BUILD_PLAN design principle
3 does not apply to it.

So this file is organised around what replaces that gate, and the two kinds are kept
apart on purpose:

* **PROVABLE** -- reproducibility, the play/undo balance, the accounting identity
  `leaves + rollouts == simulations`, the fact that every child is visited once before any
  is visited twice, that a terminal node is never rolled out, and -- with the solver on --
  that a mate in one is *never* missed once all seven children have been expanded.
* **STATISTICAL** -- how often plain UCT finds a mate in one, how often it blocks one, and
  whether the visits concentrate on a move that keeps a forced win. Those are rates over a
  sized sample, and the tests assert a floor rather than a certainty. The measured values
  live in `data/results/mcts_tactics.csv`; the floors here are deliberately below them, so
  the suite catches a regression without going amber on sampling noise.

Budgets in this file are simulation counts, never clocks: a simulation budget stops at the
same place every time and a clock does not (Phase 9's rule).
"""

